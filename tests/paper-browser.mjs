import assert from 'node:assert/strict';
import { readFile, mkdir } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { chromium } from 'playwright';
import { createApp } from '../server.mjs';
import { listen, close } from './fixture.mjs';

const require = createRequire(import.meta.url);
const browser = await chromium.launch({ executablePath: process.env.BROWSER_EXECUTABLE || '/usr/bin/chromium', headless: true, args: ['--no-sandbox'] });
const app = createApp({ store: null });
const origin = await listen(app);
let checks = 0;
const check = (condition, label) => { assert.ok(condition, label); checks++; };
const context = await browser.newContext({ viewport: { width: 1440, height: 1100 }, reducedMotion: 'reduce', acceptDownloads: true });
const page = await context.newPage();
const errors = [];
const writes = [];
page.on('pageerror', error => errors.push(error.message));
page.on('request', request => { if (request.method() === 'POST') writes.push(request.url()); });
const amount = key => page.locator(`.paper-summary [data-paper-price="${key}"]`).innerText();
try {
  await mkdir(new URL('../artifacts/', import.meta.url), { recursive: true });
  await page.goto(origin + '/#paper-order');
  await page.waitForFunction(() => !document.getElementById('paper-review-button').disabled);
  await page.evaluate(() => document.fonts.ready);
  check(await amount('upfrontTotalCents') === '$22.00', 'initial quote includes protection and booking');
  check(await amount('totalIfUsedCents') === '$322.00', 'initial quote includes later compute cost');
  await page.locator('#paper-hours').fill('200');
  check(await amount('upfrontTotalCents') === '$42.00', 'prices update with GPU-hours');
  check(await amount('totalIfUsedCents') === '$642.00', 'updated total uses shared pricing');
  await page.locator('#paper-review-button').click();
  check((await page.locator('#paper-message').innerText()).includes('too short'), 'insufficient usage window rejected');
  check(await page.locator('#paper-review').isHidden(), 'invalid request cannot reach review');
  await page.locator('#paper-hours').fill('0');
  await page.locator('#paper-review-button').click();
  check(await page.locator('#paper-hours').getAttribute('aria-invalid') === 'true', 'invalid hours are marked and focused');
  check(await page.locator('#paper-hours').evaluate(element => element === document.activeElement), 'validation focuses invalid field');
  await page.locator('#paper-hours').fill('100');
  const future = await page.locator('#paper-start').inputValue();
  await page.locator('#paper-start').fill('2020-01-01T12:00');
  await page.locator('#paper-review-button').click();
  check((await page.locator('#paper-message').innerText()).includes('future'), 'past usage window rejected');
  await page.locator('#paper-start').fill(future);
  await page.locator('#paper-review-button').click();
  check(await page.locator('#paper-review').isVisible(), 'valid request reaches review');
  check(await page.locator('#paper-review-title').evaluate(element => element === document.activeElement), 'review heading receives focus');
  check((await page.locator('#paper-review [data-paper-detail="compute"]').innerText()).includes('100 total GPU-hours'), 'review shows requested quantity');
  check((await page.locator('#paper-review [data-paper-detail="starts"]').innerText()).endsWith(' UTC'), 'usage window includes explicit timezone');
  check(await page.locator('#paper-review [data-paper-price="upfrontTotalCents"]').innerText() === '$22.00', 'review shows the upfront cost before confirmation');
  check(await page.locator('#paper-review [data-paper-price="totalIfUsedCents"]').innerText() === '$322.00', 'review shows the total cost before confirmation');
  await page.getByRole('button', { name: 'Place paper order', exact: true }).click();
  check(await page.locator('#paper-receipt').isHidden(), 'paper order needs explicit acknowledgement');
  await page.locator('#paper-edit').click();
  await page.locator('#paper-count').fill('2');
  check(await amount('upfrontTotalCents') === '$22.00', 'parallel GPU count does not double total GPU-hours');
  await page.locator('#paper-review-button').click();
  check((await page.locator('#paper-review [data-paper-detail="compute"]').innerText()).startsWith('2 × H100'), 'edit updates reviewed GPU count');
  await page.locator('#paper-confirm').check();
  await page.getByRole('button', { name: 'Place paper order', exact: true }).click();
  check(await page.locator('#paper-receipt').isVisible(), 'confirmation yields a paper receipt');
  const id = await page.locator('#paper-receipt-id').innerText();
  check(id.startsWith('PAPER-'), 'paper reference is clearly distinct from a real booking');
  check((await page.locator('#paper-message').innerText()).includes('No payment taken'), 'receipt states no payment or reservation');
  const downloadPromise = page.waitForEvent('download');
  await page.locator('#paper-download').click();
  const download = await downloadPromise;
  const receipt = JSON.parse(await readFile(await download.path(), 'utf8'));
  check(receipt.receiptId === id && receipt.status === 'simulated', 'download contains the displayed paper receipt');
  check(['paymentCharged', 'capacityHeld', 'realReservationCreated', 'persisted'].every(key => receipt[key] === false), 'receipt cannot imply payment, capacity, or durable storage');
  check(receipt.prices.totalIfUsedCents === 32200, 'receipt retains the reviewed total');
  check(writes.length === 0, 'paper order sends no server writes or waitlist submissions');
  check(await page.evaluate(() => localStorage.length === 0 && sessionStorage.length === 0), 'paper order creates no browser storage');
  await page.locator('#paper-again').click();
  check(await page.locator('#paper-fields').isVisible() && await page.locator('#paper-hours').inputValue() === '100', 'another order resets the form');
  await page.clock.install();
  await page.locator('#paper-review-button').click();
  await page.clock.fastForward(16 * 60 * 1000);
  await page.locator('#paper-confirm').check();
  await page.getByRole('button', { name: 'Place paper order', exact: true }).click();
  check(await page.locator('#paper-fields').isVisible() && (await page.locator('#paper-message').innerText()).includes('expired'), 'expired quote needs a new review');
  await page.clock.resume();
  await page.reload();
  await page.waitForFunction(() => !document.getElementById('paper-review-button').disabled);
  check(await page.locator('#paper-receipt').isHidden(), 'refresh clears paper orders');
  for (const width of [320, 390, 768, 1024, 1440]) {
    await page.setViewportSize({ width, height: 1000 });
    check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `paper form fits ${width}px`);
  }
  await page.setViewportSize({ width: 1440, height: 1100 });
  await page.locator('#paper-order').screenshot({ path: 'artifacts/paper-order-desktop.png', style: '.nav,.skip-link{visibility:hidden}' });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('#paper-order').screenshot({ path: 'artifacts/paper-order-mobile.png', style: '.nav,.skip-link{visibility:hidden}' });
  await page.locator('#paper-review-button').click();
  await page.locator('#paper-confirm').check();
  await page.getByRole('button', { name: 'Place paper order', exact: true }).click();
  check(await page.locator('#paper-receipt').isVisible(), 'paper order completes on mobile');
  const auditContext = await browser.newContext({ bypassCSP: true, viewport: { width: 390, height: 844 } });
  const audit = await auditContext.newPage();
  await audit.goto(origin);
  await audit.waitForFunction(() => !document.getElementById('paper-review-button').disabled);
  await audit.addScriptTag({ path: require.resolve('axe-core/axe.min.js') });
  const accessible = async label => {
    const result = await audit.evaluate(() => axe.run(document, { runOnly: { type: 'tag', values: ['wcag2a', 'wcag2aa', 'wcag21aa'] } }));
    check(result.violations.length === 0, label + ': ' + JSON.stringify(result.violations.map(v => ({ id: v.id, nodes: v.nodes.map(n => n.target) }))));
  };
  await audit.locator('#paper-review-button').click();
  await accessible('paper review accessibility');
  await audit.locator('#paper-confirm').check();
  await audit.getByRole('button', { name: 'Place paper order', exact: true }).click();
  await accessible('paper receipt accessibility');
  await auditContext.close();
  // Standalone preview uses exactly the same model and client, without an API.
  const offlineContext = await browser.newContext({ offline: true, viewport: { width: 390, height: 844 } });
  const offline = await offlineContext.newPage();
  await offline.setContent(await readFile(new URL('../artifacts/dodona-preview.html', import.meta.url), 'utf8'));
  await offline.waitForFunction(() => !document.getElementById('paper-review-button').disabled);
  await offline.locator('#paper-review-button').click();
  await offline.locator('#paper-confirm').check();
  await offline.getByRole('button', { name: 'Place paper order', exact: true }).click();
  check(await offline.locator('#paper-receipt').isVisible(), 'standalone preview supports complete paper orders offline');
  check(await offline.locator('#submit-button').isDisabled(), 'offline paper orders do not enable real signups');
  await offlineContext.close();
  check(errors.length === 0, 'no JavaScript errors: ' + errors.join('; '));
  console.log(JSON.stringify({ paperOrderChecksPassed: checks, serverWrites: writes.length, offlinePaperOrders: true, storage: 'browser memory only; no payments, capacity holds, or stored reservations' }, null, 2));
} finally { await context.close(); await browser.close(); await close(app); }
